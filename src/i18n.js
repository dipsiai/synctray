function pickLanguage(locale) {
  return String(locale || '').toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

function format(template, vars = {}) {
  return template.replace(/\{(\w+)\}/g, (_match, key) => (key in vars ? String(vars[key]) : ''));
}

function translator(lang) {
  const dict = STRINGS[lang] || STRINGS.en;
  return (key, vars) => format(dict[key] ?? STRINGS.en[key] ?? key, vars);
}

module.exports = { STRINGS, pickLanguage, translator };
